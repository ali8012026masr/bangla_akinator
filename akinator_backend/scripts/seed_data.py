async def seed_data():
    """Seed questions and characters idempotently."""
    db = get_database()

    # Step 1: Ensure indexes exist first
    await init_db_indexes(db)

    # Step 2: Upsert questions
    now = datetime.now(timezone.utc)
    for q in QUESTIONS:
        await db.questions.update_one(
            {"question_code": q["question_code"]},
            {
                "$set": {
                    "text_bn": q["text_bn"],
                    "text_en": q["text_en"],
                    "answer_type": q["answer_type"],
                    "active": q["active"],
                    "order": q["order"],
                    "updated_at": now
                },
                "$setOnInsert": {
                    "created_at": now
                }
            },
            upsert=True
        )
    logger.info(f"Seeded {len(QUESTIONS)} questions (idempotent upsert).")

    # Step 3: Upsert characters
    for c in CHARACTERS:
        await db.characters.update_one(
            {"normalized_name": c["normalized_name"]},
            {
                "$set": {
                    "name_bn": c["name_bn"],
                    "name_en": c["name_en"],
                    "aliases_bn": c["aliases_bn"],
                    "aliases_en": c["aliases_en"],
                    "categories": c["categories"],
                    "is_real_person": c["is_real_person"],
                    "is_alive": c["is_alive"],
                    "image_url": c["image_url"],
                    "status": c["status"],
                    "answer_profile": c["answer_profile"],
                    "updated_at": now
                },
                "$setOnInsert": {
                    "created_at": now,
                    "times_played": 0,
                    "times_guessed_correctly": 0
                }
            },
            upsert=True
        )
    logger.info(f"Seeded {len(CHARACTERS)} characters (idempotent upsert).")

    total_q = await db.questions.count_documents({})
    total_c = await db.characters.count_documents({})
    logger.info(f"Database currently contains {total_q} questions and {total_c} characters.")


if __name__ == "__main__":
    try:
        asyncio.run(seed_data())
    finally:
        asyncio.run(close_database_connection())
